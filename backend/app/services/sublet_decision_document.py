"""PDF rendering of a completed sublet request's decision record, in the same
layout as the Residential Occupancy Agreement (agreement_document/pdf.py):
brand header and footer, a cover with a reference grid, numbered sections
with the red rule, navy-header tables, callouts, and an integrity
certificate.

ZR-SUB-003 Section 7: the record carries the request ID, property/rental
reference, parties, dates, scope, conditions, decision authority, decision
timestamp and integrity metadata. Rendered on demand from the request's own
fields -- a decided SubletRequest row is never rewritten."""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.platypus import BaseDocTemplate, Frame, KeepTogether, NextPageTemplate, PageTemplate, Spacer

from app.services.agreement_document.pdf import (
    CONTENT_W, CREAM, ICON_PATH, INK, MARGIN_X, MUTED, NAVY, PAGE_H, PINK, RED, SKY,
    _callout, _grid, _p, _quarter, _section,
)

TITLE = "Sublet Decision Record"
SUBTITLE = "Record of the host's decision on a tenant's request to sublet or share a rented room"
KICKER = ("SUBLET PERMISSION", "DECISION RECORD")
PLATFORM_ROLE_TITLE = "Platform role"
PLATFORM_ROLE = (
    "Zoiko Rooms routed this request to the verified host and recorded their decision. Zoiko Rooms did not "
    "grant or refuse permission on the owner's behalf, and this record does not change any term of the "
    "underlying occupancy agreement except as the decision itself states."
)
INTEGRITY_TITLE = "Document integrity"
INTEGRITY = (
    "The content fingerprint is a SHA-256 hash of the decision fields shown in this record. Any change to "
    "those fields produces a different fingerprint, so a copy can be checked against the platform's record."
)
CLOSING_LINE = "This record was generated by Zoiko Rooms from the sublet request's stored decision."
CLOSING_SUBLINE = "Keep it with your occupancy agreement."


@dataclass
class SubletDecisionModel:
    record_ref: str
    status_label: str
    arrangement_label: str
    decided_on: str
    jurisdiction_label: str
    summary_rows: list[tuple[str, str]]
    property_rows: list[tuple[str, str]]
    party_rows: list[tuple[str, str, str, str]]
    terms_rows: list[tuple[str, str]]
    conditions: list[str]
    decision_notes: str
    history_rows: list[tuple[str, str]]
    certificate_rows: list[tuple[str, str]] = field(default_factory=list)

    @property
    def footer(self) -> str:
        return f"ZOIKO ROOMS • {self.record_ref} • {self.jurisdiction_label}"


def content_fingerprint(model: SubletDecisionModel) -> str:
    payload = {
        "ref": model.record_ref, "status": model.status_label, "arrangement": model.arrangement_label,
        "summary": model.summary_rows, "property": model.property_rows, "parties": model.party_rows,
        "terms": model.terms_rows, "conditions": model.conditions, "notes": model.decision_notes,
        "history": model.history_rows,
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True, default=str).encode()).hexdigest()


def render_sublet_decision_pdf(model: SubletDecisionModel) -> bytes:
    buffer = BytesIO()
    doc = BaseDocTemplate(
        buffer, pagesize=A4,
        leftMargin=MARGIN_X, rightMargin=MARGIN_X, topMargin=30 * mm, bottomMargin=20 * mm,
        title=f"{TITLE} {model.record_ref}", author="Zoiko Rooms", subject=SUBTITLE,
    )
    frame = Frame(MARGIN_X, 20 * mm, CONTENT_W, PAGE_H - 50 * mm, id="body", leftPadding=0, rightPadding=0,
                  topPadding=0, bottomPadding=0)
    doc.addPageTemplates([
        PageTemplate(id="first", frames=[frame], onPage=lambda c, _d: _draw_chrome(c, model, first=True)),
        PageTemplate(id="later", frames=[frame], onPage=lambda c, _d: _draw_chrome(c, model, first=False)),
    ])

    two_col = [CONTENT_W * 0.38, CONTENT_W * 0.62]
    story: list = [NextPageTemplate("later")]
    story += [
        _p(TITLE, "title"),
        _p(SUBTITLE, "subtitle"),
        Spacer(1, 5 * mm),
        _grid([["RECORD ID", "ARRANGEMENT", "STATUS", "DECIDED ON"],
               [model.record_ref, model.arrangement_label, model.status_label, model.decided_on]],
              _quarter(), header=True),
    ]
    story += _section("01", "Decision Summary")[1:]
    story += [_grid([[k.upper(), v] for k, v in model.summary_rows], two_col, header=False, label_cols=(0,)),
              Spacer(1, 5 * mm), _callout(PLATFORM_ROLE_TITLE, PLATFORM_ROLE, CREAM, RED)]

    story += _section("02", "Property and Rental")
    story.append(_grid([[k.upper(), v] for k, v in model.property_rows], two_col, header=False, label_cols=(0,)))

    story += _section("03", "Parties")
    story.append(_grid(
        [["PARTY", "NAME", "ROLE IN THIS REQUEST", "IDENTITY"]]
        + [[_p(a, "cell_bold"), b, c, d] for a, b, c, d in model.party_rows],
        [CONTENT_W * 0.2, CONTENT_W * 0.25, CONTENT_W * 0.37, CONTENT_W * 0.18], header=True,
    ))

    story += _section("04", "Arrangement and Terms")
    story.append(_grid([[k.upper(), v] for k, v in model.terms_rows], two_col, header=False, label_cols=(0,)))

    story += _section("05", "Conditions and Notes")
    if model.conditions:
        story.append(_grid([["NO.", "CONDITION"]] + [[str(i), c] for i, c in enumerate(model.conditions, start=1)],
                           [CONTENT_W * 0.1, CONTENT_W * 0.9], header=True))
    else:
        story.append(_p("No conditions were attached to this decision."))
    if model.decision_notes:
        story += [Spacer(1, 3 * mm), _callout("Host's notes", model.decision_notes, SKY, NAVY)]

    story += _section("06", "Record History")
    story.append(_grid([["DATE AND TIME (UTC)", "EVENT"]] + [[a, b] for a, b in model.history_rows],
                       [CONTENT_W * 0.3, CONTENT_W * 0.7], header=True))

    certificate = _grid([["EVIDENCE", "RECORDED VALUE"]] + [[_p(k, "cell_bold"), v] for k, v in model.certificate_rows],
                        [CONTENT_W * 0.38, CONTENT_W * 0.62], header=True)
    story += _section("07", "Integrity Certificate")
    story += [
        KeepTogether([certificate, Spacer(1, 3 * mm), _callout(INTEGRITY_TITLE, INTEGRITY, PINK, RED)]),
        Spacer(1, 8 * mm),
        _p(CLOSING_LINE, "closing"),
        _p(CLOSING_SUBLINE, "closing_sub"),
    ]
    doc.build(story)
    return buffer.getvalue()


def _draw_chrome(canvas, model: SubletDecisionModel, *, first: bool) -> None:
    """Same header/footer as the agreement PDF, with this record's own kicker."""
    canvas.saveState()
    right = MARGIN_X + CONTENT_W
    if first:
        canvas.setFillColor(RED)
        canvas.rect(MARGIN_X, PAGE_H - 12 * mm, CONTENT_W, 1.4 * mm, stroke=0, fill=1)
    y = PAGE_H - 22 * mm
    canvas.setFont("Helvetica-Bold", 15)
    canvas.setFillColor(RED)
    canvas.drawString(MARGIN_X, y, "ZOIKO")
    canvas.setFillColor(NAVY)
    canvas.setFont("Helvetica", 15)
    canvas.drawString(MARGIN_X + canvas.stringWidth("ZOIKO", "Helvetica-Bold", 15) + 0.6 * mm, y, "Rooms")
    canvas.setFont("Helvetica", 7.6)
    if first:
        canvas.setFillColor(RED)
        canvas.drawRightString(right, y + 4 * mm, KICKER[0])
        canvas.setFillColor(NAVY)
        canvas.drawRightString(right, y + 0.6 * mm, KICKER[1])
    else:
        canvas.setFillColor(NAVY)
        canvas.drawRightString(right, y + 2 * mm, TITLE.upper())

    fy = 11 * mm
    if ICON_PATH.exists():
        canvas.drawImage(str(ICON_PATH), MARGIN_X, fy - 1 * mm, width=4 * mm, height=4 * mm, mask="auto")
    canvas.setFont("Helvetica", 6.6)
    canvas.setFillColor(MUTED)
    canvas.drawString(MARGIN_X + 5.5 * mm, fy, model.footer)
    canvas.setFont("Helvetica", 7)
    canvas.drawRightString(right - 4 * mm, fy - 2.5 * mm, "Page")
    canvas.setFont("Helvetica-Bold", 10)
    canvas.setFillColor(INK)
    canvas.drawRightString(right, fy - 2.5 * mm, str(canvas.getPageNumber()))
    canvas.restoreState()


def generated_at_label() -> str:
    return datetime.now(timezone.utc).strftime("%d %b %Y, %H:%M UTC")
